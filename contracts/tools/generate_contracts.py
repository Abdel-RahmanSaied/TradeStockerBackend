"""Generates Go and Python payload code from the contract documents.

    python3 -I -B contracts/tools/generate_contracts.py          # write the files
    python3 -I -B contracts/tools/generate_contracts.py --check  # fail if any is stale or a
                                                       # contract change breaks the lock
    python3 -I -B contracts/tools/generate_contracts.py --lock   # lock new surfaces and
                                                       # non-breaking changes

Outputs (never edit them by hand):
  research/src/tradestocker_research/contract_documents.py  exact schema texts
  research/src/tradestocker_research/events_v1.py           frozen dataclasses
  internal/contracts/events_v1.go                           Go structs (gofmt)

Decimals and timestamps stay strings in both languages, so a round trip never
reformats a digit; integers are int64 / int; nullable values are pointers /
Optional. Standard library only, plus the pinned toolchain's gofmt for the Go file.
"""
import importlib.util
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
CONTRACTS = ROOT / "contracts"
EMBEDDED = ["events/v1", "research"]
PY_DOCS = ROOT / "research/src/tradestocker_research/contract_documents.py"
PY_EVENTS = ROOT / "research/src/tradestocker_research/events_v1.py"
GO_EVENTS = ROOT / "internal/contracts/events_v1.go"
HEADER = "Code generated by contracts/tools/generate_contracts.py; DO NOT EDIT."
LOCK = CONTRACTS / "compat" / "v1.lock.json"


def load_compat():
    # -I keeps this folder off sys.path, so load the module by its file path.
    spec = importlib.util.spec_from_file_location("compat", pathlib.Path(__file__).with_name("compat.py"))
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module
ENVELOPE = ["event_id", "event_type", "schema_version", "occurred_at", "published_at", "producer", "producer_build",
            "correlation_id", "causation_id", "mode", "account_id"]
INITIALISMS = {"id": "ID", "sha256": "SHA256", "url": "URL"}


def documents():
    out = {}
    for folder in EMBEDDED:
        for path in sorted((CONTRACTS / folder).glob("*.json")):
            out["%s/%s" % (folder, path.name)] = path.read_text(encoding="utf-8")
    return out


def target(base, ref):
    """The (document, pointer) a $ref names."""
    file, _, pointer = ref.partition("#")
    return (base if not file else str(pathlib.PurePosixPath(base).parent / file)), pointer


def resolve(docs, base, ref):
    name, pointer = target(base, ref)
    node = json.loads(docs[name])
    for part in [p for p in pointer.split("/") if p]:
        node = node[part]
    return name, node


MAX_REF_STEPS = 64


def follow(docs, base, schema):
    """Follows $ref while a schema has no type. A reference reached twice, or more than
    MAX_REF_STEPS of them, stops with an error instead of looping. preflight() has
    already refused such schemas with the shared compiler; this is a second guard."""
    seen: set[tuple[str, str]] = set()
    while isinstance(schema, dict) and "type" not in schema and "$ref" in schema:
        key = target(base, schema["$ref"])
        if key in seen or len(seen) >= MAX_REF_STEPS:
            raise SystemExit("contract generation: reference loop or more than %d references from %s" % (MAX_REF_STEPS, base))
        seen.add(key)
        base, schema = resolve(docs, base, schema["$ref"])
    return base, schema


def field_type(docs, base, schema):
    """Returns (kind, nullable): kind is string, integer, boolean or strings."""
    base, schema = follow(docs, base, schema)
    if "type" not in schema and "const" in schema:
        return ("boolean" if isinstance(schema["const"], bool) else "string"), False
    t = schema["type"]
    types = [t] if isinstance(t, str) else list(t)
    nullable = "null" in types
    kinds = [x for x in types if x != "null"]
    if len(kinds) != 1:
        raise SystemExit("unsupported type %r" % t)
    kind = kinds[0]
    if kind == "array":
        _, item = follow(docs, base, schema["items"])
        if not isinstance(item, dict) or item.get("type") != "string":
            raise SystemExit("only arrays of strings are generated")
        return "strings", nullable
    if kind not in ("string", "integer", "boolean"):
        raise SystemExit("unsupported field kind %r" % kind)
    return kind, nullable


def camel(name):
    return "".join(INITIALISMS.get(p, p.capitalize()) for p in name.split("_"))


def events(docs):
    out = []
    for name in sorted(docs):
        if not name.startswith("events/v1/") or not name.endswith(".v1.schema.json"):
            continue
        schema = json.loads(docs[name])
        event_type = schema["properties"]["event_type"]["const"]
        data = schema["$defs"]["data"]
        fields = [(f, field_type(docs, name, s)) for f, s in data["properties"].items()]
        out.append((event_type, camel(event_type.replace(".", "_")) + "V1", fields, schema["description"]))
    return out


GO_KIND = {"string": "string", "integer": "int64", "boolean": "bool", "strings": "[]string"}
PY_KIND = {"string": "str", "integer": "int", "boolean": "bool", "strings": "Tuple[str, ...]"}


def go_source(evs):
    lines = ["// " + HEADER, "", "package contracts", "", "import (", '\t"bytes"', '\t"encoding/json"', '\t"fmt"', ")", "",
             "// Event is a v1 event: the envelope around one typed data object.",
             "type Event[D any] struct {"]
    for f in ENVELOPE:
        go_type = "*string" if f == "account_id" else ("int64" if f == "schema_version" else "string")
        lines.append('\t%s %s `json:"%s"`' % (camel(f), go_type, f))
    lines += ['\tData D `json:"data"`', "}", ""]
    for event_type, typename, fields, desc in evs:
        lines.append("// %s is the data of %s.v1. %s" % (typename, event_type, desc))
        lines.append("type %s struct {" % typename)
        for f, (kind, nullable) in fields:
            go_type = GO_KIND[kind]
            if nullable:
                go_type = "*" + go_type
            lines.append('\t%s %s `json:"%s"`' % (camel(f), go_type, f))
        lines += ["}", ""]
    lines += [
        "// DecodeEvent checks raw with CheckEvent, then decodes it into its typed",
        "// event, such as *Event[ResearchAssessmentCompletedV1].",
        "func DecodeEvent(r *Registry, raw []byte) (any, error) {",
        "\tobj, err := CheckEvent(r, raw)",
        "\tif err != nil {",
        "\t\treturn nil, err",
        "\t}",
        '\tswitch obj["event_type"] {',
    ]
    for event_type, typename, _, _ in evs:
        lines += ['\tcase "%s":' % event_type, "\t\treturn decodeAs[%s](raw)" % typename]
    lines += [
        "\t}",
        '\treturn nil, fmt.Errorf("no generated type for event_type %v", obj["event_type"])',
        "}",
        "",
        "func decodeAs[D any](raw []byte) (*Event[D], error) {",
        "\tvar e Event[D]",
        "\td := json.NewDecoder(bytes.NewReader(raw))",
        "\td.DisallowUnknownFields()",
        "\tif err := d.Decode(&e); err != nil {",
        "\t\treturn nil, err",
        "\t}",
        "\treturn &e, nil",
        "}",
        "",
        "// EventTypes lists the v1 catalog in order.",
        "var EventTypes = []string{",
    ]
    for event_type, _, _, _ in evs:
        lines.append('\t"%s",' % event_type)
    lines += ["}", ""]
    text = "\n".join(lines)
    # The pinned toolchain's gofmt (GOTOOLCHAIN from the Makefile), so the output
    # is the same on every machine.
    goroot = subprocess.run(["go", "env", "GOROOT"], capture_output=True, check=True, text=True).stdout.strip()
    gofmt = str(pathlib.Path(goroot) / "bin" / "gofmt")
    return subprocess.run([gofmt], input=text.encode(), capture_output=True, check=True).stdout.decode()


def py_from(kind, nullable, expr):
    if kind == "integer":
        conv = "int(%s.integer())" % expr
    elif kind == "strings":
        conv = "tuple(str(x) for x in %s)" % expr
    elif kind == "boolean":
        conv = "bool(%s)" % expr
    else:
        conv = "str(%s)" % expr
    return "None if %s is None else %s" % (expr, conv) if nullable else conv


def py_to(kind, expr):
    return "list(%s)" % expr if kind == "strings" else expr


def py_source(evs):
    lines = ['"""%s\n\nv1 event payload types. Decode with decode_event; encode with encode_event.\n"""' % HEADER,
             "from dataclasses import dataclass",
             "from typing import Any, Dict, Generic, Optional, Tuple, Type, TypeVar",
             "",
             "from tradestocker_research.contracts import canonical, check_event",
             "",
             'D = TypeVar("D")',
             "",
             "",
             "@dataclass(frozen=True)",
             "class Event(Generic[D]):",
             '    """A v1 event: the envelope around one typed data object."""',
             ""]
    for f in ENVELOPE:
        py = "Optional[str]" if f == "account_id" else ("int" if f == "schema_version" else "str")
        lines.append("    %s: %s" % (f, py))
    lines += ["    data: D", "",
              "    def to_json(self) -> Dict[str, Any]:",
              "        out: Dict[str, Any] = {"]
    for f in ENVELOPE:
        lines.append('            "%s": self.%s,' % (f, f))
    lines += ['            "data": self.data.to_json(),  # type: ignore[attr-defined]', "        }", "        return out", ""]
    for event_type, typename, fields, desc in evs:
        lines += ["", "@dataclass(frozen=True)", "class %s:" % typename, '    """%s.v1: %s"""' % (event_type, desc), ""]
        for f, (kind, nullable) in fields:
            py = PY_KIND[kind]
            lines.append("    %s: %s" % (f, "Optional[%s]" % py if nullable else py))
        lines += ["", "    @classmethod", "    def from_json(cls, value: Dict[str, Any]) -> \"%s\":" % typename, "        return cls("]
        for f, (kind, nullable) in fields:
            lines.append("            %s=%s," % (f, py_from(kind, nullable, 'value["%s"]' % f)))
        lines += ["        )", "", "    def to_json(self) -> Dict[str, Any]:", "        return {"]
        for f, (kind, _) in fields:
            lines.append('            "%s": %s,' % (f, py_to(kind, "self." + f)))
        lines += ["        }", ""]
    lines += ["", "EVENT_TYPES: Dict[str, Type[Any]] = {"]
    for event_type, typename, _, _ in evs:
        lines.append('    "%s": %s,' % (event_type, typename))
    lines += ["}", "", "",
              "def decode_event(registry: Any, raw: bytes) -> Event[Any]:",
              '    """check_event, then the typed event (raises contracts.EventError)."""',
              "    value = check_event(registry, raw)",
              '    data_type = EVENT_TYPES[value["event_type"]]',
              "    fields = {f: value[f] for f in %r}" % (tuple(ENVELOPE),),
              '    fields["schema_version"] = int(value["schema_version"].integer())',
              '    fields["account_id"] = None if value["account_id"] is None else str(value["account_id"])',
              '    return Event(data=data_type.from_json(value["data"]), **fields)',
              "", "",
              "def encode_event(event: Event[Any]) -> str:",
              '    """The canonical JSON text of a typed event."""',
              "    return canonical(event.to_json())",
              ""]
    return "\n".join(lines)


def py_documents(docs):
    lines = ['"""%s\n\nThe contract documents embedded in the package; Registry(DOCUMENTS) needs no file access.\n"""' % HEADER,
             "DOCUMENTS = {"]
    for name, text in docs.items():
        lines.append("    %s: %s," % (json.dumps(name), json.dumps(text, ensure_ascii=False)))
    lines += ["}", ""]
    return "\n".join(lines)


def compatibility(check, lock_now):
    """Compares the contracts with the lock. Returns an exit code."""
    compat = load_compat()
    docs = compat.load_documents(CONTRACTS)
    lock = compat.load_lock(LOCK) if LOCK.exists() else {"dialect": compat.C.DIALECT, "surfaces": {}}
    findings = compat.check(lock, docs)
    breaking = [f for f in findings if f[5]]
    for surface, kind, effect, path, detail, is_breaking in findings:
        print("%s %s: %s %s at %s %s" % ("BREAKING" if is_breaking else "change", surface, kind, effect, path, detail), file=sys.stderr)
    if breaking:
        print("%d breaking contract change(s): publish a new version instead" % len(breaking), file=sys.stderr)
        return 1
    if lock_now:
        LOCK.parent.mkdir(exist_ok=True)
        LOCK.write_text(compat.dumps(compat.make_lock(docs)) + "\n", encoding="utf-8")
        return 0
    if check and findings:
        print("contract changes are not locked yet: review them, then run contracts/tools/generate_contracts.py --lock", file=sys.stderr)
        return 1
    return 0


def preflight():
    """Compiles every contract surface with the shared strict compiler (compat.surfaces)
    before anything is generated, formatted or written. Returns an error text or None."""
    compat = load_compat()
    try:
        compat.surfaces(compat.load_documents(CONTRACTS))
    except compat.CompatError as error:
        return str(error)
    return None


def main(argv):
    check = argv == ["--check"]
    lock_now = argv == ["--lock"]
    if argv and not check and not lock_now:
        print(__doc__, file=sys.stderr)
        return 2
    problem = preflight()
    if problem:
        print("contracts do not compile; nothing generated: " + problem, file=sys.stderr)
        return 1
    if lock_now:
        return compatibility(False, True)
    docs = documents()
    evs = events(docs)
    outputs = {PY_DOCS: py_documents(docs), PY_EVENTS: py_source(evs), GO_EVENTS: go_source(evs)}
    stale = []
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(str(path.relative_to(ROOT)))
            if not check:
                path.write_text(text, encoding="utf-8")
    if check and stale:
        print("stale generated contract code (run contracts/tools/generate_contracts.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    return compatibility(check, False)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
